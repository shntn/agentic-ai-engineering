# ベースに追加される、コンテンツタイプ別の執筆指示
WRITING_SPECIFICS: dict[ContentType, str] = {
    ContentType.BLOG: """

ブログ記事固有の指示 — 視点と経験を共有する:
- 立場を取る: 「私はXの方がYより優れていると思います、なぜなら...」
- 関連があれば武勇伝を共有する
- 気軽な調子で、個性を出す
- 技術コミュニティの会話に参加する""",
    ContentType.TUTORIAL: """

チュートリアル固有の指示 — 忍耐強いガイド役になる:
- 最後に何が得られるかから始める
- 各ステップはテスト可能であるべき
- どこでつまずきそうかを予測する
- 「エラーXが出た場合、それはおそらくYを意味します」
- 「どうやるか」だけでなく「なぜそうするか」も含める""",
    ContentType.CONCEPT: """

コンセプト解説固有の指示 — メンタルモデルを構築する:
- その概念が解決する問題から始める
- エンジニアがすでに知っている具体的な例え話を使う
- シンプルなものから複雑なものへ段階的に構築する
- 「でもなぜ単に〜しないの？」という疑問に答える
- 読者がすでに理解している概念とつなげる""",
}


def get_writing_system(content_type: ContentType) -> str:
    """タイプ別の執筆プロンプトを構築する: ベースのトーン + コンテンツタイプ別の指示。"""
    return WRITING_SYSTEM_BASE + WRITING_SPECIFICS.get(content_type, "")


# ─── 修正 ────────────────────────────────────────────────────────────────────

_REVISION_RULES = """

修正ルール:
- 提供されたフィードバックを基に下書きを修正する
- すべての問題点と提案に対応する
- 全体的な構成は維持しつつ、品質を改善する
- 著者の文体を保つ——一般的な散文に平坦化しない
- 修正済みの記事全体を返す（変更部分だけではなく）
- 修正済みの記事のみを出力する——前置き、コメント、「修正版はこちらです」のような文言は不要

WEB検索:
- Web検索を使用できます。フィードバックで言及されている、検証や追加の詳細が必要な特定の\
事実・API・概念を調べる場合にのみ使用してください
- セクションをゼロから書き直したり、新しい切り口を見つけたりするために検索を使わないでください
- フィードバックが追加のリサーチを必要としない場合は、検索を完全にスキップしてください"""


def get_revision_system(content_type: ContentType) -> str:
    """修正用プロンプトを構築する: ベースのトーン + タイプ別の指示 + 修正ルール。"""
    return get_writing_system(content_type) + _REVISION_RULES


